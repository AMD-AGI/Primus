export FLUX_FP4_DEOSC_LOG_FREQ=${FLUX_FP4_DEOSC_LOG_FREQ:-1}
export FLUX_FP4_RHT=${FLUX_FP4_RHT:-0}
if [ "${FLUX_FP4_FORWARD:-0}" = "1" ]; then
  unset FLUX_FP4_FPROP_CAST
else
  export FLUX_FP4_FPROP_CAST=${FLUX_FP4_FPROP_CAST:-a6w4}
fi
export FLUX_FP4_WEIGHT_2D=${FLUX_FP4_WEIGHT_2D:-0}
export FLUX_FP4_SAVE_QUANTIZED=${FLUX_FP4_SAVE_QUANTIZED:-1}
export FLUX_FP8_DUAL_PACK=${FLUX_FP8_DUAL_PACK:-1}
export FLUX_FP8_DUAL_DELAYED=${FLUX_FP8_DUAL_DELAYED:-1}

export FLUX_FP8_FUSE_BIAS_EPILOGUE=${FLUX_FP8_FUSE_BIAS_EPILOGUE:-1}
export FLUX_FUSED_DGELU_LEGPACK=${FLUX_FUSED_DGELU_LEGPACK:-1}
export PRIMUS_MXFP4_BIAS_FOLD=${PRIMUS_MXFP4_BIAS_FOLD:-1}
export FLUX_MXFP4_PACKED_SCALES=${FLUX_MXFP4_PACKED_SCALES:-1}
if [[ "${PRIMUS_MXFP4_BIAS_FOLD}" != "1" && "${FLUX_MXFP4_PACKED_SCALES}" == "1" ]]; then
    echo "config_common: FLUX_MXFP4_PACKED_SCALES needs PRIMUS_MXFP4_BIAS_FOLD=1; forcing it off"
    export FLUX_MXFP4_PACKED_SCALES=0
fi
export FLUX_FUSED_ADAMW=${FLUX_FUSED_ADAMW:-0}
export FLUX_LOCAL_ADAMW=${FLUX_LOCAL_ADAMW:-1}
export FLUX_FUSED_DGELU_MLP=${FLUX_FUSED_DGELU_MLP:-1}
export FLUX_FP8_AG_FUSED_QUANT=${FLUX_FP8_AG_FUSED_QUANT:-1}
export FLUX_FP4_QKV_WGRAD_BF16=${FLUX_FP4_QKV_WGRAD_BF16:-0}
export FLUX_FP4_BF16_LAST_BLOCKS=${FLUX_FP4_BF16_LAST_BLOCKS:-0}
export FLUX_FP4_BF16_FIRST_BLOCKS=${FLUX_FP4_BF16_FIRST_BLOCKS:-0}
export FLUX_FP4_BF16_MLP_ONLY=${FLUX_FP4_BF16_MLP_ONLY:-0}
export FLUX_FP4_BF16_EVAL=${FLUX_FP4_BF16_EVAL:-0}
if [ "${FLUX_FP4_BF16_EVAL}" = "1" ] && [ "${FLUX_FP4_ALL_GATHER:-1}" = "1" ]; then
  echo "config_common.sh: FLUX_FP4_BF16_EVAL=1 forces FLUX_FP4_ALL_GATHER=0 (the gathered weight" \
       "carries no real values for a bf16 eval forward)" >&2
  export FLUX_FP4_ALL_GATHER=0
fi
export FLUX_FPROP_SWITCH_PRECOMPILE=${FLUX_FPROP_SWITCH_PRECOMPILE:-1}
if [ -n "${FLUX_FPROP_SWITCH_STEP:-}" ] && [ "${FLUX_FPROP_SWITCH_PRECOMPILE}" != "1" ] && [ "${FLUX_FP4_ALL_GATHER:-1}" = "1" ]; then
  echo "config_common.sh: FLUX_FPROP_SWITCH_STEP=${FLUX_FPROP_SWITCH_STEP} with FLUX_FPROP_SWITCH_PRECOMPILE=0 forces FLUX_FP4_ALL_GATHER=0" >&2
  export FLUX_FP4_ALL_GATHER=0
fi
export FLUX_FP4_GEMM_BACKEND=${FLUX_FP4_GEMM_BACKEND:-flydsl}
export FLUX_FP4_DISPATCH=${FLUX_FP4_DISPATCH:-fusion}
export FLUX_MXFP4_P3_GEMM=${FLUX_MXFP4_P3_GEMM:-auto}
export FLUX_A6W4_AG_PIPELINE=${FLUX_A6W4_AG_PIPELINE:-0}
export FLUX_A6W4_FWD_FP4_MLP=${FLUX_A6W4_FWD_FP4_MLP:-0}

export FLUX_MXFP4_TURBO_PACKED=${FLUX_MXFP4_TURBO_PACKED:-1}
export FLUX_A6W4_GELU_PACK=${FLUX_A6W4_GELU_PACK:-1}
export FLUX_A6W4_GELU_PACK_DOUBLE=${FLUX_A6W4_GELU_PACK_DOUBLE:-1}
export FLUX_A6W4_LNMOD_PACK=${FLUX_A6W4_LNMOD_PACK:-0}
export FLUX_A6W4_LEGS_ONE_LAUNCH=${FLUX_A6W4_LEGS_ONE_LAUNCH:-1}
export FLUX_A6W4_GELU_DUAL=${FLUX_A6W4_GELU_DUAL:-1}
export ATTENTION_BACKEND=${ATTENTION_BACKEND:-flash_attn_aiter}
export PIN_FLUX_T5_STACK=1
export GRADIENT_CHECKPOINTING=${GRADIENT_CHECKPOINTING:-false}
export COMPILE_TRANSFORMER_BLOCKS=${COMPILE_TRANSFORMER_BLOCKS:-true}
export COMPILE_STRATEGY=per_block
export COMPILE_BACKEND=inductor
export COMPILE_FULLGRAPH=true
export COMPILE_DYNAMIC=false
export COMPILE_OUTPUT_HEAD=false
export FSDP2_RESHARD_AFTER_FORWARD=false
export FSDP2_REDUCE_DTYPE=${FSDP2_REDUCE_DTYPE:-bf16}
export FLUX_FP8_ALL_GATHER=${FLUX_FP8_ALL_GATHER:-1}
export FLUX_COLPACK_REGROUP_OP=${FLUX_COLPACK_REGROUP_OP:-1}
export FLUX_AG_COLPACK_KMAJOR=${FLUX_AG_COLPACK_KMAJOR:-1}
