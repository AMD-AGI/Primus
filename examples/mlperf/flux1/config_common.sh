export GPU_FORCE_BLIT_COPY_SIZE=${GPU_FORCE_BLIT_COPY_SIZE:-512}
# 4 hardware queues and 2 connections let the reduce-scatter stream leave the
# compute queue. 2 queues puts that collective on the same queue as the GEMMs.
export GPU_MAX_HW_QUEUES=${GPU_MAX_HW_QUEUES:-4}
export CUDA_DEVICE_MAX_CONNECTIONS=${CUDA_DEVICE_MAX_CONNECTIONS:-2}

export NCCL_NVLS_ENABLE=0
export NCCL_GRAPH_REGISTER=${NCCL_GRAPH_REGISTER:-0}
export NCCL_LOCAL_REGISTER=${NCCL_LOCAL_REGISTER:-0}

export NCCL_MIN_P2P_NCHANNELS=${NCCL_MIN_P2P_NCHANNELS:-32}
export NCCL_MIN_CTAS=${NCCL_MIN_CTAS:-32}
export NCCL_NCHANNELS_PER_NET_PEER=${NCCL_NCHANNELS_PER_NET_PEER:-32}

