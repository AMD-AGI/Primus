export FLUX_ATTN_DOUBLE_SPLIT=${FLUX_ATTN_DOUBLE_SPLIT:-1}
export FLUX_ATTN_SINGLE_DV_COPYROW=${FLUX_ATTN_SINGLE_DV_COPYROW:-1}
export FLUX_ATTN_LSE_BHS=${FLUX_ATTN_LSE_BHS:-1}
export FLUX_FP8_AG_PREQUANT=${FLUX_FP8_AG_PREQUANT:-gather}
export FLUX_FP8_AG_PREQUANT_CHECK=${FLUX_FP8_AG_PREQUANT_CHECK:-0}
export FLUX_FSDP_RS_COPY_IN=${FLUX_FSDP_RS_COPY_IN:-side}
export FLUX_FSDP_RS_COPY_CHECK=${FLUX_FSDP_RS_COPY_CHECK:-0}
export FLUX_FWD_GELU_PACK=${FLUX_FWD_GELU_PACK:-1}
export FLUX_GATE_DGATE=${FLUX_GATE_DGATE:-1}
export FLUX_LN_MOD_BWD=${FLUX_LN_MOD_BWD:-1}
export PRIMUS_TURBO_DGATE_ACC_ATOMIC=${PRIMUS_TURBO_DGATE_ACC_ATOMIC:-0}
export FLUX_GATE_STRIDED=${FLUX_GATE_STRIDED:-1}
export FLUX_FP4_FP8_GEMM_BACKEND=${FLUX_FP4_FP8_GEMM_BACKEND:-flydsl}
export FLUX_PERFORMANCE_MODE=${FLUX_PERFORMANCE_MODE:-nemo_mlperf}
export MLPERF_ENABLE=${MLPERF_ENABLE:-true}
export MLPERF_WARMUP_TRAIN_STEPS=2
export MLPERF_WARMUP_VALIDATION_STEPS=2
export MLPERF_CLEAR_CACHES=${MLPERF_CLEAR_CACHES:-true}
export TARGET_ACCURACY=${TARGET_ACCURACY:-0.586}
export VAL_CHECK_INTERVAL=${VAL_CHECK_INTERVAL:-262144}
# 1-node MLPerf recipe evaluates at the train microbatch, not batch 1.
export EVAL_BATCH_SIZE=${EVAL_BATCH_SIZE:-${LOCAL_BATCH_SIZE:-32}}
# copy runs the parameter all-gather on the GPU copy engines. symm is the 6.1
# symmetric-memory path; torch 2.16 cannot find its NCCL host communicator.
export FSDP_ALL_GATHER_IMPL=${FSDP_ALL_GATHER_IMPL:-copy}
export SEED=${SEED:-10007}
export ENABLE_WANDB_LOGGER=false
export LOG_FREQ=${LOG_FREQ:-999999}
export FLUX_LIGHT_LOG=${FLUX_LIGHT_LOG:-0}
export FLUX_LIGHT_LOG_REORDER=${FLUX_LIGHT_LOG_REORDER:-0}
export DATALOADER_NUM_WORKERS=${DATALOADER_NUM_WORKERS:-8}
export EVAL_DATALOADER_NUM_WORKERS=${EVAL_DATALOADER_NUM_WORKERS:-$DATALOADER_NUM_WORKERS}
export EVAL_DATALOADER_PREFETCH_FACTOR=${EVAL_DATALOADER_PREFETCH_FACTOR:-4}
export SAVE_STEPS=0
export SAVE_STRATEGY=${SAVE_STRATEGY:-none}
export CHECKPOINT_KEEP_LATEST=0
export RESUME_FROM_CHECKPOINT=${RESUME_FROM_CHECKPOINT-}
export PROFILE=${PROFILE:-false}
export PROFILE_RANK=${PROFILE_RANK:-0}
export PROFILE_WAIT_STEPS=${PROFILE_WAIT_STEPS:-25}
