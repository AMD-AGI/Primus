export FSDP_SDMA_MODULES=${FSDP_SDMA_MODULES:-single_blocks}

export FLUX_FSDP_FWD_PREFETCH=${FLUX_FSDP_FWD_PREFETCH:-0}
# Keep enough reduce-scatter inputs in flight that the compute stream does not
# wait out each collective, and run that collective on a normal-priority stream
# so it uses a different hardware queue from the GEMMs. Both need the queue
# settings above; neither alone changes the step time.
export FLUX_FSDP_RS_MAX_BUFFERS=${FLUX_FSDP_RS_MAX_BUFFERS:-32}
export FLUX_FSDP_RS_STREAM=${FLUX_FSDP_RS_STREAM:-normal}

export NCCL_IB_HCA=${NCCL_IB_HCA:-ionic_0,ionic_1,ionic_2,ionic_3,ionic_4,ionic_5,ionic_6,ionic_7}
export NCCL_IB_GID_INDEX=${NCCL_IB_GID_INDEX:-1}

export GPUS_PER_NODE=8
export MAX_STEPS=${MAX_STEPS:-30000}
export FLUX_FLOAT8_RECIPE=tensorwise
if [ "${FLUX_FP4_FORWARD:-0}" = "1" ]; then
  export FLUX_FP4_PASSES=all
else
  export FLUX_FP4_PASSES=dgrad,wgrad
fi
export FLUX_FP4_HADAMARD=${FLUX_FP4_HADAMARD:-16}
export FLUX_FP4_SR_PASSES=${FLUX_FP4_SR_PASSES:-}
export FLUX_FP4_SR_OPERANDS=${FLUX_FP4_SR_OPERANDS:-}
