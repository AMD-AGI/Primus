#!/usr/bin/env bash

export GPUS_PER_NODE=8
export MAX_STEPS=${MAX_STEPS:-30000}
export FLUX_TRAINING_RECIPE=${FLUX_TRAINING_RECIPE:-fp8}

case "$FLUX_TRAINING_RECIPE" in
  fp8)
    export FLUX_FLOAT8_RECIPE=tensorwise
    export FLUX_MXFP4_RECIPE=
    export FLUX_FP8_ALL_GATHER=${FLUX_FP8_ALL_GATHER:-1}
    export FLUX_MXFP8_ALL_GATHER=0
    export PRIMUS_FLUX_REUSE_FP8_INPUT=${PRIMUS_FLUX_REUSE_FP8_INPUT:-1}
    ;;
  mxfp8)
    export FLUX_FLOAT8_RECIPE=
    export FLUX_MXFP4_RECIPE=custom
    export FLUX_MXFP4_FORWARD_PRECISION=mxfp8
    export FLUX_MXFP4_BACKWARD_PRECISION=mxfp8
    export FLUX_FP8_ALL_GATHER=0
    export FLUX_MXFP8_ALL_GATHER=${FLUX_MXFP8_ALL_GATHER:-1}
    export PRIMUS_FLUX_REUSE_FP8_INPUT=0
    export PRIMUS_TURBO_GEMM_BACKEND=${PRIMUS_TURBO_GEMM_BACKEND:-FP4:AITER,FP8:FLYDSL}
    export PRIMUS_TURBO_AUTO_TUNE=${PRIMUS_TURBO_AUTO_TUNE:-0}
    ;;
  *)
    echo "Unsupported FLUX_TRAINING_RECIPE=$FLUX_TRAINING_RECIPE" >&2
    return 2
    ;;
esac

export FLUX_FP8_QKV_WGRAD_HIGH_PRECISION=${FLUX_FP8_QKV_WGRAD_HIGH_PRECISION:-true}
export FLUX_MXFP4_FORWARD_PRECISION=${FLUX_MXFP4_FORWARD_PRECISION:-mxfp4}
export FLUX_MXFP4_BACKWARD_PRECISION=${FLUX_MXFP4_BACKWARD_PRECISION:-mxfp4}
export FLUX_MXFP4_FORWARD_HADAMARD=${FLUX_MXFP4_FORWARD_HADAMARD:-none}
