export COMPILE_FULLGRAPH=true
export COMPILE_DYNAMIC=false
export COMPILE_OUTPUT_HEAD=false
export FSDP2_RESHARD_AFTER_FORWARD=false
export FSDP2_REDUCE_DTYPE=bf16
export FSDP_ALL_GATHER_BACKEND=${FSDP_ALL_GATHER_BACKEND:-rccl}
export FSDP_SDMA_MODULES=${FSDP_SDMA_MODULES:-single_blocks}
if [[ "$FSDP_ALL_GATHER_BACKEND" == "rccl_sdma" ]]; then
  export FLUX_SDMA_ATTACH=1
  export GPU_FORCE_BLIT_COPY_SIZE=${GPU_FORCE_BLIT_COPY_SIZE:-512}
  export NCCL_CTA_POLICY=${NCCL_CTA_POLICY:-2}
  export NCCL_CUMEM_ENABLE=${NCCL_CUMEM_ENABLE:-1}
  export NCCL_LOCAL_REGISTER=${NCCL_LOCAL_REGISTER:-0}
  export NCCL_CROSS_NIC=${NCCL_CROSS_NIC:-2}
  export NCCL_DMABUF_ENABLE=${NCCL_DMABUF_ENABLE:-1}
  export NCCL_SYM_GIN_KERNELS_ENABLE=${NCCL_SYM_GIN_KERNELS_ENABLE:-0}
  export NCCL_HIER_CE_COLL_NUM_CTX=${NCCL_HIER_CE_COLL_NUM_CTX:-1}
  export NCCL_MIN_P2P_NCHANNELS=${NCCL_MIN_P2P_NCHANNELS:-32}
  export NCCL_MIN_CTAS=${NCCL_MIN_CTAS:-32}
  export NCCL_NCHANNELS_PER_NET_PEER=${NCCL_NCHANNELS_PER_NET_PEER:-32}
  export TORCH_NCCL_USE_TENSOR_REGISTER_ALLOCATOR_HOOK=true
fi
export FLUX_PERFORMANCE_MODE=${FLUX_PERFORMANCE_MODE:-nemo_mlperf}
export MLPERF_ENABLE=${MLPERF_ENABLE:-true}
export MLPERF_WARMUP_TRAIN_STEPS=2
export MLPERF_WARMUP_VALIDATION_STEPS=2
export MLPERF_CLEAR_CACHES=${MLPERF_CLEAR_CACHES:-true}
export TARGET_ACCURACY=0.586
