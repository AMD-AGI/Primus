export PROFILE_ACTIVE_STEPS=${PROFILE_ACTIVE_STEPS:-3}
export PROFILE_WITH_STACK=${PROFILE_WITH_STACK:-false}
if [[ "${PROFILE}" == "true" ]]; then
    export ROCPROFILER_QUEUE_INTERPOSITION=${ROCPROFILER_QUEUE_INTERPOSITION:-0}
fi
export FLUX_STEP_TIMING=${FLUX_STEP_TIMING:-0}
export FLUX_STEP_TIMING_EVERY=${FLUX_STEP_TIMING_EVERY:-10}
export FLUX_AG_TIMING=${FLUX_AG_TIMING:-0}
export FLUX_PROFILE_MEMORY=${FLUX_PROFILE_MEMORY:-1}

export FLUX_FUSED_NORM_ROPE=${FLUX_FUSED_NORM_ROPE:-1}
export FLUX_FUSED_NORM_ROPE_BWD_BLOCK_M=${FLUX_FUSED_NORM_ROPE_BWD_BLOCK_M:-8}
export FLUX_ROPE_TABLES_BF16=${FLUX_ROPE_TABLES_BF16:-1}
export FLUX_ATTN_REGION=${FLUX_ATTN_REGION:-1}
export FLUX_FP8_CSTORE_PER_SHAPE=${FLUX_FP8_CSTORE_PER_SHAPE:-1}
export FLUX_ATTN_FLYDSL=${FLUX_ATTN_FLYDSL:-1}
export FLUX_TIMESTEP_NOSYNC=${FLUX_TIMESTEP_NOSYNC:-1}
export FLUX_FP8_GEMM_BACKEND=${FLUX_FP8_GEMM_BACKEND:-selective_flydsl}
