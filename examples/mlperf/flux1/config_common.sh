export FLUX_MXFP4_ACTIVATION_RESIDUAL=${FLUX_MXFP4_ACTIVATION_RESIDUAL:-none}
export FLUX_MXFP4_ACTIVATION_RESIDUAL_DTYPE=${FLUX_MXFP4_ACTIVATION_RESIDUAL_DTYPE:-bf16}
export FLUX_MXFP4_EVAL_PRECISION=${FLUX_MXFP4_EVAL_PRECISION:-same}
export FLUX_MXFP4_GRADIENT_SR=${FLUX_MXFP4_GRADIENT_SR:-false}
export ATTENTION_BACKEND=flash_attn_aiter
export PIN_FLUX_T5_STACK=1
export GRADIENT_CHECKPOINTING=true
export COMPILE_TRANSFORMER_BLOCKS=true
