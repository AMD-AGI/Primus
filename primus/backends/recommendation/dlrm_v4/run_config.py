"""Translate a Primus recommendation/dlrm_v4 module config into what the DLRMv4 trainer reads.

The trainer (``recommendation/generative_recommenders``) is configured by a gin
file plus environment variables that the gin file reads (``env_int`` /
``env_float`` / ``env_path`` macros) and a few that the launcher reads. A config
value of ``null`` leaves the gin default in place, so the gin file stays the one
source of truth for the model and kernel settings.

Pure functions only (no torch, no GPU): unit-tested in
tests/unit_tests/backends/recommendation.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Optional

# Primus param -> environment variable the trainer reads.
ENV_PARAMS: Dict[str, str] = {
    "data_path": "DLRM_DATA_PATH",
    "seed": "SEED",
    "batch_size": "BATCH_SIZE",
    "dense_lr": "DENSE_LR",
    "sparse_lr": "SPARSE_LR",
    "lr_warmup_steps": "LR_WARMUP_STEPS",
    "skip_eval_epoch_pct": "SKIP_EVAL_EPOCH_PCT",
    "eval_every_data_pct": "EVAL_EVERY_DATA_PCT",
    "eval_every_n_windows": "EVAL_EVERY_N_WINDOWS",
    "auc_threshold": "AUC_THRESHOLD",
    "start_ts": "START_TS",
    "num_train_ts": "NUM_TRAIN_TS",
    "num_train_batches": "NUM_TRAIN_BATCHES",
    "num_eval_batches": "NUM_EVAL_BATCHES",
    "num_workers": "NUM_WORKERS",
    "prefetch_factor": "PREFETCH_FACTOR",
    "eval_num_workers": "EVAL_NUM_WORKERS",
    "history_length": "HISTORY_LENGTH",
    "hbm_cap_gb": "HBM_CAP_GB",
    "metric_log_freq": "METRIC_LOG_FREQ",
    "run_name": "RUN_NAME",
    "ckpt_path": "CKPT_PATH",
    "output_trace": "OUTPUT_TRACE",
    "mlperf_logging": "MLPERF_LOGGING",
    "mlperf_log_path": "MLPERF_LOG_PATH",
    "submission_platform": "MLPERF_SUBMISSION_PLATFORM",
}

# Datasets the trainer ships a gin file for (train_ranker.SUPPORTED_CONFIGS).
GIN_DIR = Path("generative_recommenders") / "dlrm_v4" / "train" / "gin"

# The staged yambda-5b cache the data loader reads, relative to the data path.
CACHE_SUBDIR = "processed_5b/hstu_cache_L{history_length}"
DEFAULT_HISTORY_LENGTH = 4086


def env_value(value: Any) -> str:
    """Environment form of a config value: booleans as 1/0, the rest as str."""
    if isinstance(value, bool):
        return "1" if value else "0"
    return str(value)


def build_env(params: Mapping[str, Any]) -> Dict[str, str]:
    """Environment variables for the set (non-null) run-shape params."""
    env: Dict[str, str] = {}
    for key, name in ENV_PARAMS.items():
        value = params.get(key)
        if value is None or value == "":
            continue
        env[name] = env_value(value)
    return env


def gin_file_text(base_gin: str, bindings: Optional[Iterable[str]]) -> str:
    """A gin file that includes the dataset's gin file, then adds bindings.

    Later bindings win in gin, so these override the base file's values.
    """
    lines = [
        "# Generated by Primus (primus/backends/recommendation/dlrm_v4). Do not edit.",
        f"include '{base_gin}'",
    ]
    for binding in bindings or []:
        binding = str(binding).strip()
        if binding:
            lines.append(binding)
    return "\n".join(lines) + "\n"


def resolve_gin_file(backend_root: Path, dataset: str, gin_file: Optional[str]) -> Path:
    """The gin file to start from: an explicit path, else the dataset's file."""
    if gin_file:
        path = Path(gin_file).expanduser()
        if not path.is_absolute():
            path = backend_root / path
        return path
    from_name = {
        "yambda-5b": "yambda_5b.gin",
        "debug": "debug.gin",
    }
    name = from_name.get(dataset, dataset.replace("-", "_") + ".gin")
    return backend_root / GIN_DIR / name


def cache_dir(data_path: str, history_length: Optional[int]) -> Path:
    """The staged sequence cache the trainer opens."""
    return Path(data_path) / CACHE_SUBDIR.format(history_length=history_length or DEFAULT_HISTORY_LENGTH)


def missing_data(data_path: Optional[str], history_length: Optional[int]) -> List[str]:
    """What the trainer needs under data_path but cannot find (empty when ready)."""
    if not data_path:
        return ["data_path is not set (DLRM_DATA_PATH)"]
    root = Path(data_path)
    needed = [
        cache_dir(data_path, history_length),
        root / "shared_metadata" / "album_item_mapping.parquet",
        root / "shared_metadata" / "artist_item_mapping.parquet",
    ]
    return [str(p) for p in needed if not p.exists()]


def mlperf_run_started(log_path: str) -> bool:
    """True once the MLPerf log holds the run_start event."""
    try:
        with open(log_path, errors="replace") as f:
            return any('"run_start"' in line for line in f)
    except OSError:
        return False


def run_summary(log_path: str) -> Dict[str, Any]:
    """Time to train, status and evals from an MLPerf log (empty if absent)."""
    import json

    events: Dict[str, list] = {}
    try:
        with open(log_path, errors="replace") as f:
            for line in f:
                if ":::MLLOG" not in line:
                    continue
                try:
                    event = json.loads(line.split(":::MLLOG", 1)[1])
                except ValueError:
                    continue
                events.setdefault(event.get("key"), []).append(event)
    except OSError:
        return {}
    summary: Dict[str, Any] = {}
    if "init_start" in events and "run_start" in events:
        summary["init_s"] = (events["run_start"][0]["time_ms"] - events["init_start"][0]["time_ms"]) / 1000
    if "run_start" in events and "run_stop" in events:
        summary["run_s"] = (events["run_stop"][0]["time_ms"] - events["run_start"][0]["time_ms"]) / 1000
        summary["status"] = (events["run_stop"][0].get("metadata") or {}).get("status")
    if "eval_accuracy" in events:
        summary["evals"] = len(events["eval_accuracy"])
        summary["last_auc"] = events["eval_accuracy"][-1].get("value")
    return summary


def default_mlperf_log(output_dir: str) -> str:
    return os.path.join(output_dir, "mlperf_dlrm_v4.log")
